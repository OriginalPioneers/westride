export type LanguageCode = keyof typeof LANGUAGES;

export const LANGUAGE_CODES = Object.keys(LANGUAGES) as [
  LanguageCode,
  ...LanguageCode[],
];

export function isLanguageCode(code: string): code is LanguageCode {
  return Object.hasOwn(LANGUAGES, code);
}

export function languageName(code: string): string {
  return isLanguageCode(code) ? LANGUAGES[code] : code;
}

/** Sorted by name, for pickers. */
export const LANGUAGE_OPTIONS = LANGUAGE_CODES.map((code) => ({
  value: code,
  label: LANGUAGES[code],
})).sort((a, b) => a.label.localeCompare(b.label, "en"));
